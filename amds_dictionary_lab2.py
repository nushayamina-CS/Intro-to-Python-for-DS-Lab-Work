# Problem 20: Automated Voting System

candidates = {
    "alice": 0,
    "bob": 0,
    "charlie": 0
}

rejected_votes = 0

print("Voting System")
print("Enter candidate names (Alice, Bob, Charlie).")
print("The system will automatically process results after 3 votes.")

# Loop exactly 3 times instead of a while loop
for i in range(1, 4):
    vote = input(f"Vote {i}/3: ").lower()

    if vote in candidates:
        candidates[vote] += 1
    else:
        rejected_votes += 1

print("\nVote Count:")
for candidate, votes in candidates.items():
    print(candidate.capitalize(), ":", votes)

total_valid_votes = 0
for votes in candidates.values():
    total_valid_votes += votes

print("Total Valid Votes:", total_valid_votes)
print("Rejected Votes:", rejected_votes)

if total_valid_votes == 0:
    print("No valid votes were submitted.")
else:
    print("\nVote Percentages:")
    for candidate, votes in candidates.items():
        percentage = (votes / total_valid_votes) * 100
        print(candidate.capitalize(), ":", round(percentage, 2), "%")

    highest_votes = None
    winners = []

    for candidate, votes in candidates.items():
        if highest_votes is None or votes > highest_votes:
            highest_votes = votes
            winners = [candidate]
        elif votes == highest_votes:
            winners.append(candidate)

    if len(winners) == 1:
        print("Winner:", winners[0].capitalize())
    else:
        print("Tie between:", ", ".join(name.capitalize() for name in winners))